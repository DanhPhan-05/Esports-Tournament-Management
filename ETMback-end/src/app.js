import "dotenv/config";
import express from "express";
import cookieParser from "cookie-parser";
import cors from "cors";
import helmet from "helmet";
import morgan from "morgan";
import passport from "passport";
import { policyRateLimit } from "./middlewares/securityPolicy.js";
import { configurePassport } from "./config/passport.js";
import authRoutes from "./routes/auth.routes.js";
import userRoutes from "./routes/user.routes.js";
import clubRoutes from "./routes/club.routes.js";
import tournamentRoutes from "./routes/tournament.routes.js";
import applicationRoutes from "./routes/application.routes.js";
import matchRoutes from "./routes/match.routes.js";
import adminRoutes from "./routes/admin.routes.js";
import predictionRoutes from "./routes/prediction.routes.js";
import publicRoutes from "./routes/public.routes.js";
import protestRoutes from "./routes/protest.routes.js";
import backlogRoutes from "./routes/backlog.routes.js";
import { authenticate } from "./middlewares/auth.js";
import { upload, checkUploadSize } from "./middlewares/upload.js";
import { uploadAsset } from "./controllers/upload.controller.js";
import { asyncHandler } from "./utils/asyncHandler.js";
import { csrfProtection, issueCsrfToken } from "./middlewares/csrf.js";
import { errorHandler, notFound } from "./middlewares/errorHandler.js";

const app = express();
app.set("trust proxy", 1);
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_URL?.split(",") || "http://localhost:5173", credentials: true }));
app.use(express.json({ limit: "1mb" })); app.use(express.urlencoded({ extended: true })); app.use(cookieParser(process.env.COOKIE_SECRET));
app.use(morgan(process.env.NODE_ENV === "production" ? "combined" : "dev"));
configurePassport(); app.use(passport.initialize());
app.get("/api/csrf-token", issueCsrfToken);
app.use(csrfProtection);
app.get("/api/health", (_req, res) => res.json({ success: true, service: "ETM API" }));
app.use("/api", policyRateLimit);
app.use("/api/auth", authRoutes);
app.use("/api", publicRoutes);
app.use("/api", backlogRoutes);
app.post("/api/uploads", authenticate, upload.single("file"), checkUploadSize, asyncHandler(uploadAsset));
app.use("/api/users", userRoutes);
app.use("/api/clubs", clubRoutes);
app.use("/api/tournaments", tournamentRoutes);
app.use("/api/applications", applicationRoutes);
app.use("/api/matches", matchRoutes);
app.use("/api/predictions", predictionRoutes);
app.use("/api/protests", protestRoutes);
app.use("/api/admin", adminRoutes);
app.use(notFound); app.use(errorHandler);
export default app;
