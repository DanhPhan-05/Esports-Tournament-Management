import { Router } from "express";
import * as tournament from "../controllers/tournament.controller.js";
import * as bracketController from "../controllers/bracket.controller.js";
import * as standingController from "../controllers/standing.controller.js";
import { authenticate, authorize } from "../middlewares/auth.js";
import { asyncHandler } from "../utils/asyncHandler.js";
import { matches } from "../controllers/public.controller.js";
const router = Router();
router.get("/", asyncHandler(tournament.publicList));
router.get("/regions", asyncHandler(tournament.regions));
router.get("/:id", asyncHandler(tournament.publicGet));
router.get("/:tournamentId/bracket", asyncHandler(bracketController.getBracket));
router.get("/:tournamentId/brackets", asyncHandler(bracketController.getBracket));
router.get("/:tournamentId/matches", asyncHandler(matches));
router.get("/:tournamentId/standings", asyncHandler(standingController.standings));
router.get("/manage/mine", authenticate, authorize("TournamentOrganizer", "Administrator"), asyncHandler(tournament.organizerList));
router.post("/manage", authenticate, authorize("TournamentOrganizer"), asyncHandler(tournament.createTournament));
router.patch("/manage/:id", authenticate, authorize("TournamentOrganizer", "Administrator"), asyncHandler(tournament.updateTournament));
router.patch("/manage/:id/status", authenticate, authorize("TournamentOrganizer", "Administrator"), asyncHandler(tournament.changeStatus));
router.post("/:tournamentId/bracket", authenticate, authorize("TournamentOrganizer", "Administrator"), asyncHandler(bracketController.generateBracket));
router.post("/:tournamentId/bracket/publish", authenticate, authorize("TournamentOrganizer", "Administrator"), asyncHandler(bracketController.publishBracket));
router.get("/:tournamentId/report", authenticate, authorize("TournamentOrganizer", "Administrator"), asyncHandler(standingController.tournamentReport));
router.get("/:tournamentId/reports", authenticate, authorize("TournamentOrganizer", "Administrator"), asyncHandler(standingController.tournamentReport));
router.post("/:tournamentId/brackets", authenticate, authorize("TournamentOrganizer", "Administrator"), asyncHandler(bracketController.generateBracket));
export default router;
