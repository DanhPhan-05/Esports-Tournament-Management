import { Router } from "express";
import * as accountController from "../controllers/account.controller.js";
import * as auditRecordController from "../controllers/auditRecord.controller.js";
import * as banController from "../controllers/ban.controller.js";
import * as clubController from "../controllers/club.controller.js";
import * as gameController from "../controllers/game.controller.js";
import * as templateController from "../controllers/notificationTemplate.controller.js";
import { authenticate, authorize } from "../middlewares/auth.js";
import { asyncHandler } from "../utils/asyncHandler.js";
import * as content from "../controllers/content.controller.js";
import * as reports from "../controllers/violationReport.controller.js";
import * as policies from "../controllers/securityPolicy.controller.js";
const router = Router(); router.use(authenticate, authorize("Administrator"));
router.get("/accounts", asyncHandler(accountController.listAccounts));
router.post("/accounts", asyncHandler(accountController.createStaffAccount));
router.get("/accounts/:id", asyncHandler(accountController.getAccount));
router.put("/accounts/:id", asyncHandler(accountController.updateAccount));
router.delete("/accounts/:id", asyncHandler(accountController.disableAccount));
router.post("/accounts/:id/resend-activation", asyncHandler(accountController.resendActivation));
router.patch("/accounts/:id/status", asyncHandler(accountController.updateAccountStatus));
router.post("/clubs", asyncHandler(clubController.createClub));
router.get("/clubs", asyncHandler(clubController.listMyClubs));
router.put("/clubs/:id", asyncHandler(clubController.updateAdminClub));
router.delete("/clubs/:id", asyncHandler(clubController.deactivateClub));
router.post("/clubs/:id/managers", asyncHandler(clubController.assignClubManager));
router.get("/games", asyncHandler(gameController.listGames));
router.post("/games", asyncHandler(gameController.saveGame));
router.patch("/games/:id", asyncHandler(gameController.saveGame));
router.put("/games/:id", asyncHandler(gameController.saveGame));
router.delete("/games/:id", asyncHandler(gameController.deactivateGame));
router.get("/notification-templates", asyncHandler(templateController.listTemplates));
router.put("/notification-templates", asyncHandler(templateController.saveTemplate));
router.get("/notifications", asyncHandler(templateController.listTemplates));
router.post("/notifications", asyncHandler(templateController.saveTemplate));
router.put("/notifications/:id", asyncHandler(templateController.saveTemplate));
router.delete("/notifications/:id", asyncHandler(templateController.disableTemplate));
router.post("/bans", asyncHandler(banController.createBan));
router.get("/bans", asyncHandler(banController.listBans));
router.put("/bans/:id", asyncHandler(banController.updateBan));
router.delete("/bans/:id", asyncHandler(banController.revokeBan));
router.patch("/bans/:id/revoke", asyncHandler(banController.revokeBan));
router.get("/audit-records", asyncHandler(auditRecordController.auditLog));
router.get("/audit-log", asyncHandler(auditRecordController.auditLog));
router.get("/content", asyncHandler(content.listContent));
router.get("/content/:id", asyncHandler(content.getContent));
router.post("/content", asyncHandler(content.saveContent));
router.put("/content/:id", asyncHandler(content.saveContent));
router.delete("/content/:id", asyncHandler(content.archiveContent));
router.get("/reports", asyncHandler(reports.listReports));
router.put("/reports/:id", asyncHandler(reports.reviewReport));
router.get("/security-policies", asyncHandler(policies.listPolicies));
router.put("/security-policies/:category", asyncHandler(policies.updatePolicy));
export default router;
