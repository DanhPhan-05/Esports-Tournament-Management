import { Router } from "express";
import * as controller from "../controllers/club.controller.js";
import * as teamController from "../controllers/team.controller.js";
import * as memberController from "../controllers/clubMember.controller.js";
import { authenticate, authorize } from "../middlewares/auth.js";
import { asyncHandler } from "../utils/asyncHandler.js";
import * as publicController from "../controllers/public.controller.js";
const router = Router();
router.get("/", asyncHandler(publicController.clubs));
router.get("/my", authenticate, authorize("ClubManager", "Administrator"), asyncHandler(controller.listMyClubs));
router.get("/mine", authenticate, authorize("ClubManager", "Administrator"), asyncHandler(controller.listMyClubs));
router.get("/manage/:clubId", authenticate, authorize("ClubManager", "Administrator"), asyncHandler(controller.getClub));
router.get("/:clubId", asyncHandler(publicController.club));
router.use(authenticate, authorize("ClubManager", "Administrator"));
router.patch("/:clubId", asyncHandler(controller.updateClub));
router.get("/:clubId/teams", asyncHandler(teamController.listTeams));
router.post("/:clubId/teams", asyncHandler(teamController.createTeam));
router.patch("/:clubId/teams/:teamId", asyncHandler(teamController.updateTeam));
router.get("/:clubId/members", asyncHandler(memberController.listMembers));
router.post("/:clubId/members", asyncHandler(memberController.createMember));
router.patch("/:clubId/members/:memberId", asyncHandler(memberController.updateMember));
router.put("/:clubId/members/:memberId", asyncHandler(memberController.updateMember));
router.delete("/:clubId/members/:memberId", asyncHandler(memberController.endMember));
export default router;
