// Canonical backlog endpoints. Existing week-6 URLs remain available as aliases.
import { Router } from "express";
import { RosterChangeRequest, Team } from "../models/index.js";
import { authenticate, authorize } from "../middlewares/auth.js";
import { asyncHandler } from "../utils/asyncHandler.js";
import { ApiError } from "../utils/ApiError.js";
import * as applications from "../controllers/tournamentApplication.controller.js";
import * as rosters from "../controllers/roster.controller.js";
import * as changes from "../controllers/rosterChangeRequest.controller.js";
import * as tournaments from "../controllers/tournament.controller.js";
import * as brackets from "../controllers/bracket.controller.js";
import * as teams from "../controllers/team.controller.js";
import * as clubs from "../controllers/club.controller.js";
import * as notifications from "../controllers/notification.controller.js";
import { verifyEmail } from "../controllers/auth.controller.js";

const router = Router();
const staff = [authenticate, authorize("TournamentOrganizer", "Administrator")];
const manager = [authenticate, authorize("ClubManager", "Administrator")];
const status = (value) => (req, _res, next) => { req.body.status = value; next(); };
const bind = (field) => (req, _res, next) => { req.params.id = req.params[field]; next(); };
router.get("/auth/activate/:key", (req, res) => res.redirect(`${process.env.CLIENT_URL}/activate?token=${encodeURIComponent(req.params.key)}`));
router.get("/auth/verify-email", asyncHandler(verifyEmail));
router.get("/tournaments/my", ...staff, asyncHandler(tournaments.organizerList));
router.get("/tournaments/manage/:id", ...staff, asyncHandler(tournaments.managedGet));
router.post("/tournaments", authenticate, authorize("TournamentOrganizer"), asyncHandler(tournaments.createTournament));
router.put("/tournaments/:id", ...staff, asyncHandler(tournaments.updateTournament));
for (const [action, value] of [["publish", "RegistrationOpen"], ["postpone", "Postponed"], ["cancel", "Cancelled"], ["close", "RegistrationClosed"]]) router.post(`/tournaments/:id/${action}`, ...staff, status(value), asyncHandler(tournaments.changeStatus));
router.get("/tournaments/:tournamentId/brackets/manage", ...staff, asyncHandler(brackets.getManagedBracket));
router.put("/brackets/:id", ...staff, asyncHandler(brackets.updateBracket));
router.post("/tournaments/:tournamentId/brackets/publish", ...staff, asyncHandler(brackets.publishBracket));
router.get("/tournaments/:tournamentId/applications", ...staff, asyncHandler(applications.tournamentApplications));
router.get("/tournaments/:tournamentId/applications/:appId", ...staff, bind("appId"), asyncHandler(applications.applicationDetail));
for (const [action, value] of [["approve", "Approved"], ["reject", "Rejected"], ["request-info", "NeedMoreInfo"]]) router.put(`/tournaments/:tournamentId/applications/:appId/${action}`, ...staff, bind("appId"), status(value), asyncHandler(applications.reviewApplication));
router.get("/applications/my", ...manager, asyncHandler(applications.myApplications));
router.get("/applications/:id", authenticate, authorize("ClubManager", "TournamentOrganizer", "Administrator"), asyncHandler(applications.applicationDetail));
router.put("/applications/:id", ...manager, asyncHandler(applications.updateApplication));
router.post("/applications/:id/withdraw", ...manager, asyncHandler(applications.withdrawApplication));
router.get("/rosters", authenticate, authorize("ClubManager", "TournamentOrganizer", "Administrator"), asyncHandler(rosters.listRosters));
router.post("/rosters", ...manager, asyncHandler(rosters.createRoster));
router.get("/rosters/:id", authenticate, authorize("ClubManager", "TournamentOrganizer", "Administrator"), asyncHandler(rosters.getRoster));
router.get("/rosters/:rosterId/changes", authenticate, authorize("ClubManager", "TournamentOrganizer", "Administrator"), asyncHandler(changes.listRosterChanges));
router.put("/rosters/:id", ...manager, asyncHandler(rosters.updateRoster));
router.post("/rosters/:id/emergency-change", ...manager, asyncHandler(changes.createRosterChange));
router.get("/tournaments/:tournamentId/rosters", ...staff, asyncHandler(rosters.listRosters));
router.get("/tournaments/:tournamentId/rosters/:rosterId", ...staff, bind("rosterId"), asyncHandler(rosters.getRoster));
for (const [action, value] of [["approve", "Approved"], ["reject", "Rejected"]]) router.put(`/rosters/:id/${action}`, ...staff, status(value), asyncHandler(rosters.reviewRoster));
router.put("/rosters/:rosterId/emergency-approve", ...staff, asyncHandler(async (req, _res, next) => {
  const request = await RosterChangeRequest.findOne({ _id: req.body.requestId, rosterId: req.params.rosterId });
  if (!request) throw new ApiError(404, "Roster change request not found");
  req.params.id = request._id; req.body.status = "Approved"; next();
}), asyncHandler(changes.reviewRosterChange));
router.post("/clubs", ...manager, asyncHandler(clubs.createClub));
router.put("/clubs/:clubId", ...manager, asyncHandler(clubs.updateClub));
const teamScope = asyncHandler(async (req, _res, next) => { const team = await Team.findById(req.params.id); if (!team) throw new ApiError(404, "Team not found"); req.params.clubId = team.clubId; req.params.teamId = team._id; next(); });
router.put("/teams/:id", ...manager, teamScope, asyncHandler(teams.updateTeam));
router.delete("/teams/:id", ...manager, teamScope, asyncHandler(teams.deactivateTeam));
router.get("/notifications", authenticate, asyncHandler(notifications.listNotifications));
router.put("/notifications/:id/read", authenticate, asyncHandler(notifications.markNotificationRead));
export default router;
